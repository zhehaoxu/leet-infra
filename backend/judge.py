"""Judge engine: execute user-submitted code inside the dedicated eval venv.

The user's code is written to a temp directory as ``solution.py`` together with
the problem's ``test_cases.py`` and a generated ``runner.py``. The runner
executes every ``check_*`` function, then prints a single JSON payload marked
with ``RESULT_MARKER`` on the last line of stdout. Everything before the marker
is treated as user stdout and surfaced back to the frontend.
"""

from __future__ import annotations

import json
import os
import subprocess
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

EVAL_PYTHON = os.environ.get(
    "EVAL_PYTHON", str(ROOT / ".venv-eval" / "bin" / "python")
)
RUN_TIMEOUT_S = int(os.environ.get("JUDGE_TIMEOUT_S", "30"))

RESULT_MARKER = "###JUDGE_RESULT###"

SETUP_HINT = (
    "评测环境未找到（EVAL_PYTHON 指向的解释器不存在）。"
    "请先运行 scripts/setup_eval_env.sh 创建 .venv-eval。"
)

RUNNER_SRC = '''\
"""Auto-generated by backend/judge.py - runs one submission's test cases."""
import inspect
import json
import sys
import time
import traceback

RESULT_MARKER = "###JUDGE_RESULT###"
MODE = (sys.argv[1] if len(sys.argv) > 1 else "submit").lower()


def emit(payload):
    sys.stdout.write("\\n" + RESULT_MARKER + json.dumps(payload, ensure_ascii=False) + "\\n")
    sys.stdout.flush()


try:
    import torch
except Exception:
    emit({
        "fatal": "environment",
        "error": traceback.format_exc(limit=8),
        "cases": [],
    })
    sys.exit(0)

torch.manual_seed(42)

try:
    import solution  # user submitted code
except SyntaxError:
    emit({
        "fatal": "syntax",
        "error": "SyntaxError: " + traceback.format_exc(limit=1).strip().splitlines()[-1],
        "cases": [],
    })
    sys.exit(0)
except Exception:
    emit({
        "fatal": "import",
        "error": traceback.format_exc(limit=12),
        "cases": [],
    })
    sys.exit(0)

import test_cases

solve = getattr(solution, "solve", None)
if not callable(solve):
    emit({
        "fatal": "no_solve",
        "error": "未找到 solve 函数。请实现题目要求的 def solve(...) 签名。",
        "cases": [],
    })
    sys.exit(0)

checks = [
    (name, fn)
    for name, fn in inspect.getmembers(test_cases, inspect.isfunction)
    if name.startswith("check_") and fn.__module__ == test_cases.__name__
]
# keep source order of definition
checks.sort(key=lambda item: inspect.getsourcelines(item[1])[1])

if MODE == "run":
    # 运行模式只跑样例用例；若题库未标记任何样例则回退为全部
    examples = [(n, f) for n, f in checks if getattr(f, "example", False)]
    if examples:
        checks = examples

cases = []
for name, fn in checks:
    torch.manual_seed(42)
    t0 = time.perf_counter()
    passed = True
    message = None
    try:
        fn(solve)
    except AssertionError:
        passed = False
        tb = traceback.format_exc().strip().splitlines()
        message = tb[-1].strip() if tb else "assertion failed"
        if message.startswith("AssertionError"):
            message = message[len("AssertionError"):].lstrip(": ")
    except Exception:
        passed = False
        tb = traceback.format_exc().strip().splitlines()
        message = tb[-1].strip() if tb else "unexpected error"
    cases.append({
        "name": name[len("check_"):],
        "passed": passed,
        "message": message,
        "elapsed_ms": round((time.perf_counter() - t0) * 1000, 2),
    })

emit({"fatal": None, "error": None, "cases": cases, "mode": MODE})
'''


def _failure(status: str, error: str) -> dict:
    return {
        "status": status,
        "accepted": False,
        "passed": 0,
        "total": 0,
        "cases": [],
        "stdout": "",
        "error": error,
        "elapsed_ms": None,
    }


def run_judgement(code: str, test_cases_src: str, mode: str = "submit") -> dict:
    """Run ``code`` as solution.py against ``test_cases_src`` in the eval env.

    mode="run" 只执行样例用例；mode="submit" 执行全部用例。
    """
    result = _run_judgement(code, test_cases_src, mode)
    result["mode"] = mode
    return result


def _run_judgement(code: str, test_cases_src: str, mode: str) -> dict:
    if not Path(EVAL_PYTHON).exists():
        return _failure("env_missing", SETUP_HINT)

    env = os.environ.copy()
    env["CUDA_VISIBLE_DEVICES"] = ""
    env["PYTHONHASHSEED"] = "0"
    # keep the runner's own interpreter noise away from stdout parsing
    env["PYTHONDONTWRITEBYTECODE"] = "1"

    t0 = time.perf_counter()
    with tempfile.TemporaryDirectory(prefix="leet-infra-judge-") as tmp:
        tmp_path = Path(tmp)
        (tmp_path / "solution.py").write_text(code, encoding="utf-8")
        (tmp_path / "test_cases.py").write_text(test_cases_src, encoding="utf-8")
        (tmp_path / "runner.py").write_text(RUNNER_SRC, encoding="utf-8")
        try:
            proc = subprocess.run(
                [EVAL_PYTHON, "-u", "runner.py", mode],
                cwd=tmp,
                capture_output=True,
                text=True,
                timeout=RUN_TIMEOUT_S,
                env=env,
            )
        except subprocess.TimeoutExpired:
            return _failure(
                "timeout",
                f"运行超时（>{RUN_TIMEOUT_S}s）。检查是否存在死循环或过大的计算规模。",
            )
        stdout, stderr = proc.stdout, proc.stderr
    elapsed_ms = round((time.perf_counter() - t0) * 1000, 1)

    marker_pos = stdout.rfind(RESULT_MARKER)
    if marker_pos < 0:
        detail = (stderr or stdout or "").strip()
        return _failure(
            "crashed",
            f"评测进程异常退出（exit={proc.returncode}）。\n{detail}",
        )

    user_stdout = stdout[:marker_pos].rstrip("\n")
    payload_line = stdout[marker_pos + len(RESULT_MARKER):].splitlines()[0]
    try:
        payload = json.loads(payload_line)
    except json.JSONDecodeError:
        return _failure("crashed", "评测结果解析失败（runner 输出损坏）。")

    if payload.get("fatal"):
        return {
            "status": payload["fatal"],
            "accepted": False,
            "passed": 0,
            "total": 0,
            "cases": [],
            "stdout": user_stdout,
            "error": payload.get("error"),
            "elapsed_ms": elapsed_ms,
        }

    cases = payload.get("cases", [])
    accepted = bool(cases) and all(c["passed"] for c in cases)
    passed = sum(1 for c in cases if c["passed"])
    return {
        "status": "accepted" if accepted else "wrong_answer",
        "accepted": accepted,
        "passed": passed,
        "total": len(cases),
        "cases": cases,
        "stdout": user_stdout,
        "error": None,
        "elapsed_ms": elapsed_ms,
    }
