# ---------- shared helpers ----------


def _close(a, b, tol=1e-9):
    return abs(a - b) <= tol


def _assert_close_list(got, want, tol=1e-9):
    assert len(got) == len(want), (len(got), len(want))
    for i, (g, w) in enumerate(zip(got, want)):
        assert _close(g, w, tol), (i, g, w)


def _assert_close_2d(got, want, tol=1e-9):
    got = np.asarray(got)
    assert got.shape == (len(want), len(want[0])), (got.shape, len(want), len(want[0]))
    for i in range(len(want)):
        _assert_close_list([float(v) for v in got[i]], want[i], tol)


def _assert_close_3d(got, want, tol=1e-9):
    got = np.asarray(got)
    assert got.ndim == 3 and got.shape[0] == len(want) and got.shape[1] == len(want[0])
    for b in range(len(want)):
        for l in range(len(want[b])):
            _assert_close_list([float(v) for v in got[b, l]], want[b][l], tol)


def _fix():
    f = EXPECTED["F1"]
    return (np.array(f["x"]), np.array(f["lp_w"]), np.array(f["router_w"]),
            np.array(f["hps"]))


# ---------- mode="router_probs" ----------


def check_router_probs(solve):
    f = EXPECTED["F1"]
    x, lp_w, router_w, hps = _fix()
    hidden = x @ lp_w.T
    probs = solve(mode="router_probs", hidden=hidden,
                  router_weight=router_w)
    _assert_close_3d(probs, f["probs"])
    # softmax 性质: 每 token 概率和 1
    s = np.asarray(probs).sum(axis=-1)
    assert np.allclose(s, 1.0, atol=1e-9)
    # 数据依赖: 不同 token 的 expert 分布不同（fixture 非退化）
    assert not np.allclose(probs[0, 0], probs[0, 1])


# ---------- mode="expert_mix" ----------


def check_expert_mix(solve):
    f = EXPECTED["F1"]
    x, lp_w, router_w, hps = _fix()
    pm = np.array(f["probs_mean"])
    combined = solve(mode="expert_mix", probs_mean=pm, hps=hps)
    _assert_close_2d(combined, f["combined"])
    # 显式展开: combined = sum_e pm[e] * hps[e]
    manual = sum(pm[e] * hps[e] for e in range(hps.shape[0]))
    assert np.allclose(np.asarray(combined), manual, atol=1e-12)


# ---------- mode="forward_delta" ----------


def check_forward_delta(solve):
    f = EXPECTED["F1"]
    x, lp_w, router_w, hps = _fix()
    got = solve(mode="forward_delta", x=x, lp_weight=lp_w,
                router_weight=router_w, hps=hps)
    _assert_close_3d(got, f["forward"])
    got_mlp = solve(mode="forward_delta", x=x, lp_weight=lp_w,
                    router_weight=router_w, hps=hps, mlp=True)
    _assert_close_3d(got_mlp, f["forward_mlp"])
    # 互证: forward = sum_e p_mean[e] * (hidden @ hps[e])
    hidden = x @ lp_w.T
    pm = np.array(f["probs_mean"])
    manual = sum(pm[e] * (hidden @ hps[e]) for e in range(hps.shape[0]))
    _assert_close_3d(got, manual.tolist())
    # mlp 分支与 identity 分支可观测地不同（ReLU 作用于负分量）
    assert not np.allclose(np.asarray(got), np.asarray(got_mlp))


# ---------- mode="monoscale_delta" ----------


def check_monoscale_delta(solve):
    f = EXPECTED["F1"]
    x, lp_w, router_w, hps = _fix()
    got = solve(mode="monoscale_delta", x=x, lp_weight=lp_w, hps=hps)
    _assert_close_3d(got, f["monoscale"])
    got_mlp = solve(mode="monoscale_delta", x=x, lp_weight=lp_w, hps=hps,
                    mlp=True)
    _assert_close_3d(got_mlp, f["monoscale_mlp"])
    # 互证: combined = sum(hps, 0) / ne
    manual = (x @ lp_w.T) @ (hps.sum(axis=0) * (1.0 / hps.shape[0]))
    _assert_close_3d(got, manual.tolist())


# ---------- mode="lp_groups" ----------


def check_lp_groups(solve):
    t = EXPECTED["lp"]
    for key, (n, ne) in (("n12_ne4", (12, 4)), ("n12_ne3", (12, 3)),
                         ("n6_ne4", (6, 4)), ("n5_ne2", (5, 2))):
        got = solve(mode="lp_groups", n_layers=n, ne=ne)
        assert got["stride"] == t[key]["stride"], (key, got)
        assert got["lp_group"] == t[key]["lp_group"], (key, got)
        assert got["num_lp"] == t[key]["num_lp"], (key, got)
    # 尾组收纳: n=5, ne=2 -> stride=2 -> 3 个 LP（idx 4 落组 2）
    g = solve(mode="lp_groups", n_layers=5, ne=2)
    assert g["lp_group"][-1] == 2 and g["num_lp"] == 3


