def check_tri_shifted_formula(solve):
    all_f = KW_TRI_SHIFT["all_freqs"]
    f_pts = KW_TRI_SHIFT["f_pts"]
    fd = [f_pts[i + 1] - f_pts[i] for i in range(len(f_pts) - 1)]
    want = []
    for f in all_f:
        row = []
        for j in range(len(f_pts) - 2):
            down = -(f_pts[j] - f) / fd[j]
            up = (f_pts[j + 2] - f) / fd[j + 1]
            row.append(max(0.0, min(down, up)))
        want.append(row)
    _near(C(solve, "triangular", **KW_TRI_SHIFT), want, "tri slope formula")


