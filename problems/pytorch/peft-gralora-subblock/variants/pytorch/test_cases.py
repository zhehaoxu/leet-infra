def check_split_dims(solve):
    d = solve(mode="split_dims", in_features=6, out_features=8, r=4, k=2,
              hybrid_r=0, alpha=8)
    assert d["gralora_rank"] == EXPECTED["FIX1"]["dims"]["gralora_rank"] == 4
    assert d["sub_rank"] == 2 and d["sub_in"] == 3 and d["sub_out"] == 4
    assert _close(d["scaling"], EXPECTED["FIX1"]["dims"]["scaling"])

    d2 = solve(mode="split_dims", in_features=8, out_features=8, r=4, k=2,
               hybrid_r=2, alpha=8)
    assert d2["gralora_rank"] == 2 and d2["sub_rank"] == 1
    # scaling 用总秩 r（含 hybrid）: 8/4 = 2, 而非 8/2
    assert _close(d2["scaling"], EXPECTED["FIX2"]["dims"]["scaling"])
    assert _close(d2["scaling"], 2.0)

    d3 = solve(mode="split_dims", in_features=12, out_features=9, r=6, k=3,
               hybrid_r=0, alpha=12)
    assert d3["gralora_rank"] == 6 and d3["sub_rank"] == 2
    assert d3["sub_in"] == 4 and d3["sub_out"] == 3
    assert _close(d3["scaling"], EXPECTED["FIX3"]["dims"]["scaling"])

    # 校验: r <= 0
    try:
        solve(mode="split_dims", in_features=6, out_features=8, r=0, k=2,
              hybrid_r=0, alpha=8)
        raise AssertionError("r=0 must raise")
    except ValueError:
        pass
    # 校验: gralora_rank % k != 0
    try:
        solve(mode="split_dims", in_features=6, out_features=8, r=5, k=2,
              hybrid_r=0, alpha=8)
        raise AssertionError("r=5,k=2 must raise")
    except ValueError:
        pass


