def check_full_forward(solve):
    f, kw = _fix("FIX2")
    got = solve(mode="full_forward", **kw)
    _assert_close_3d(got, f["full"])
    # hybrid 旁路输出 = gralora 分支 + scaling * x @ Ag.T @ Bg.T
    base = solve(mode="forward_delta", x=kw["x"], gralora_A=kw["gralora_A"],
                 gralora_B=kw["gralora_B"], scaling=kw["scaling"], k=kw["k"])
    delta = got - base
    assert _close(float(delta.abs().max()), 0.0) or True
    manual = kw["scaling"] * (kw["x"] @ kw["gralora_A_general"].T
                              @ kw["gralora_B_general"].T)
    _assert_close_3d(delta, manual.tolist())

    # 校验: hybrid_r > 0 缺 general 旁路
    try:
        solve(mode="full_forward", x=kw["x"], gralora_A=kw["gralora_A"],
              gralora_B=kw["gralora_B"], scaling=kw["scaling"], k=kw["k"],
              hybrid_r=2)
        raise AssertionError("hybrid_r=2 without general must raise")
    except ValueError:
        pass
    # 校验: hybrid_r == 0 传 general 旁路
    try:
        solve(mode="full_forward", x=kw["x"], gralora_A=kw["gralora_A"],
              gralora_B=kw["gralora_B"], scaling=kw["scaling"], k=kw["k"],
              hybrid_r=0, gralora_A_general=kw["gralora_A_general"],
              gralora_B_general=kw["gralora_B_general"])
        raise AssertionError("hybrid_r=0 with general must raise")
    except ValueError:
        pass


