# ---------- shared helpers ----------


def _close(a, b, tol=1e-9):
    return abs(a - b) <= tol


def _assert_close_list(got, want, tol=1e-9):
    assert len(got) == len(want), (len(got), len(want))
    for i, (g, w) in enumerate(zip(got, want)):
        assert _close(g, w, tol), (i, g, w)


def _assert_close_2d(got, want, tol=1e-9):
    assert got.shape == (len(want), len(want[0])), (got.shape, len(want), len(want[0]))
    for i in range(len(want)):
        _assert_close_list([float(v) for v in got[i]], want[i], tol)


def _assert_close_3d(got, want, tol=1e-9):
    assert got.dim() == 3 and got.shape[0] == len(want) and got.shape[1] == len(want[1])
    for b in range(len(want)):
        for l in range(len(want[b])):
            _assert_close_list([float(v) for v in got[b, l]], want[b][l], tol)


def _fix(name):
    """从锚点重建 fixture 张量（float64）。"""
    f = EXPECTED[name]
    dims = f["dims"]
    kw = dict(
        x=torch.tensor(f["x"], dtype=torch.float64),
        gralora_A=torch.tensor(f["A"], dtype=torch.float64),
        gralora_B=torch.tensor(f["B"], dtype=torch.float64),
        scaling=dims["scaling"],
        k={"FIX1": 2, "FIX2": 2, "FIX3": 3}[name],
        hybrid_r={"FIX1": 0, "FIX2": 2, "FIX3": 0}[name],
    )
    if "Ag" in f:
        kw["gralora_A_general"] = torch.tensor(f["Ag"], dtype=torch.float64)
        kw["gralora_B_general"] = torch.tensor(f["Bg"], dtype=torch.float64)
    return f, kw


