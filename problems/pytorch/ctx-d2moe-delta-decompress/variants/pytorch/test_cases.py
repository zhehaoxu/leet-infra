def _close(a, b, tol=1e-9):
    return abs(a - b) <= tol


def _assert_close_list(got, want, tol=1e-9):
    assert len(got) == len(want), (len(got), len(want))
    for i, (g, w) in enumerate(zip(got, want)):
        assert _close(g, w, tol), (i, g, w)


def _assert_close_2d(got, want, tol=1e-9):
    got = np.asarray(got)
    assert got.shape == (len(want), len(want[0])), (got.shape, len(want), len(want[0]))
    for i in range(len(want)):
        _assert_close_list([float(v) for v in got[i]], want[i], tol)


def _assert_close_3d(got, want, tol=1e-9):
    got = np.asarray(got)
    assert got.ndim == 3 and got.shape[0] == len(want) and got.shape[1] == len(want[0])
    for b in range(len(want)):
        for l in range(len(want[b])):
            _assert_close_list([float(v) for v in got[b, l]], want[b][l], tol)


def _fix():
    f = EXPECTED["F1"]
    return (f, [np.array(W) for W in f["W"]["w1"]], np.array(f["scale"]["w1"]))


# ---------- mode="fisher_merge" ----------


def check_fisher_merge(solve):
    f, W1, _ = _fix()
    base, deltas, coef = solve(mode="fisher_merge", weights=W1,
                               fisher=f["fisher"]["w1"], freq=f["freq"])
    _assert_close_2d(base, f["base"]["w1"])
    for j in range(f["m"]):
        _assert_close_2d(deltas[j], (W1[j] - np.array(f["base"]["w1"])).tolist())
    _assert_close_list([float(v) for v in coef], f["coef"]["w1"])
    # 归一化: coef 和为 1；fisher=0 专家系数为 0（不贡献 base）
    assert abs(sum(coef) - 1.0) < 1e-12
    bf, df, cf = solve(mode="fisher_merge", weights=W1,
                       fisher=[0.0, 1.0], freq=f["freq"])
    assert abs(cf[0]) < 1e-15
    assert np.allclose(np.asarray(bf), W1[1])
    # delta 方向: W - base（不是 base - W）
    assert not np.allclose(np.asarray(deltas[0]),
                           (np.array(f["base"]["w1"]) - W1[0]))


# ---------- mode="delta_rank" ----------


def check_delta_rank(solve):
    f, W1, _ = _fix()
    for case in f["rank_cases"]:
        got = solve(mode="delta_rank", shape=case["shape"], ratio=case["ratio"])
        assert got == case["k"], (case, got)
    # 参数预算语义: ratio=1 时 k = rc/(r+c) 仍小于满秩
    assert solve(mode="delta_rank", shape=[8, 6], ratio=1.0) == 3
    assert 3 < min(8, 6)


# ---------- mode="ta_svd_split" ----------


def check_ta_svd_split(solve):
    f, W1, scale = _fix()
    base = np.array(f["base"]["w1"])
    delta = W1[0] - base
    k = solve(mode="delta_rank", shape=[8, 6], ratio=0.7)
    Ws = delta @ scale
    U, S, Vt = np.linalg.svd(Ws, full_matrices=False)
    scale_inv = np.linalg.inv(scale)
    svd_u, svd_v = solve(mode="ta_svd_split", u_k=U[:, :k], sigma_k=S[:k],
                         vt_k=Vt[:k], scale_inv=scale_inv)
    # 互证: 拆分乘积 == 白化域截断 SVD 重建去白化
    manual = (U[:, :k] @ np.diag(S[:k]) @ Vt[:k]) @ scale_inv
    assert np.allclose(np.asarray(svd_u) @ np.asarray(svd_v), manual, atol=1e-10)
    # sqrt(Σ) 两侧各一次: 形状 (8,k)/(k,6)
    assert np.asarray(svd_u).shape == (8, k) and np.asarray(svd_v).shape == (k, 6)


# ---------- mode="shared_v_split" ----------


def check_shared_v_split(solve):
    f, W1, _ = _fix()
    sh = f["sharedV"]["w1"]
    r, c = 8, 6
    # 从锚点重建堆叠矩阵的 SVD 因子做显式入参
    stack = np.concatenate([(W1[j] - np.array(f["base"]["w1"])) for j in range(f["m"])], axis=0)
    k = sh["k"]
    # 互证: U_j @ V_shared == 堆叠低秩重建的行切片（V 与 U 都走 solve）
    stack_factors = np.linalg.svd(stack, full_matrices=False)
    V, U_list = solve(mode="shared_v_split", us=stack_factors[0],
                      sigma_s=stack_factors[1], vts_s=stack_factors[2],
                      seg=r, num_basis=k)
    _assert_close_2d(V, sh["V"])
    assert np.asarray(V).shape == (k, c)
    recon = (stack_factors[0][:, :k] @ np.diag(stack_factors[1][:k]) @ stack_factors[2][:k])
    for j in range(f["m"]):
        Uj = np.array(sh["U"][j])
        assert np.asarray(Uj).shape == (r, k)
        seg = stack[j * r:(j + 1) * r]
        # 低秩重建锚点（用完整 SVD 现算，仅作互证参照）
        recon_seg = recon[j * r:(j + 1) * r]
        assert np.allclose(Uj @ np.asarray(V), recon_seg, atol=1e-9), (j,)
        # 行切片偏移可观测: j>=1 的段起点是 j*r（错位变异在 j=0 不可见）
        _assert_close_2d(U_list[j], sh["U"][j])
        assert not np.allclose(np.asarray(U_list[j]),
                               stack_factors[0][j:j + r, :k])


