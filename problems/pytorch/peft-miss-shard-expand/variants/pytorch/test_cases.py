# ---------- shared helpers ----------


def _close(a, b, tol=1e-9):
    return abs(a - b) <= tol


def _assert_close_list(got, want, tol=1e-9):
    assert len(got) == len(want), (len(got), len(want))
    for i, (g, w) in enumerate(zip(got, want)):
        assert _close(g, w, tol), (i, g, w)


def _assert_close_2d(got, want, tol=1e-9):
    assert got.shape == (len(want), len(want[0])), (got.shape, len(want), len(want[0]))
    for i in range(len(want)):
        _assert_close_list([float(v) for v in got[i]], want[i], tol)


def _assert_close_3d(got, want, tol=1e-9):
    assert got.dim() == 3 and got.shape[0] == len(want) and got.shape[1] == len(want[0])
    for b in range(len(want)):
        for l in range(len(want[b])):
            _assert_close_list([float(v) for v in got[b, l]], want[b][l], tol)


def _t(name):
    f = EXPECTED[name]
    kw = dict(
        miss_block=torch.tensor(f["miss_block"], dtype=torch.float64),
        r=f["r"],
    )
    if "x" in f:
        kw["x"] = torch.tensor(f["x"], dtype=torch.float64)
    if "w0" in f:
        kw["w0"] = torch.tensor(f["w0"], dtype=torch.float64)
    if f.get("mini_r"):
        kw["mini_r"] = f["mini_r"]
        kw["out_features"] = f["out_f"]
        kw["init_weights"] = "mini"
    if name == "F3":
        kw["padded_in"] = 8  # pad 后的输入维
    return f, kw


