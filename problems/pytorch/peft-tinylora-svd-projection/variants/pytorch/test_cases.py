# ---------- shared helpers ----------


def _close(a, b, tol=1e-9):
    return abs(a - b) <= tol


def _assert_close_list(got, want, tol=1e-9):
    assert len(got) == len(want), (len(got), len(want))
    for i, (g, w) in enumerate(zip(got, want)):
        assert _close(g, w, tol), (i, g, w)


def _assert_close_2d(got, want, tol=1e-9):
    assert got.shape == (len(want), len(want[0])), (got.shape, len(want), len(want[0]))
    for i in range(len(want)):
        _assert_close_list([float(v) for v in got[i]], want[i], tol)


def _assert_close_3d(got, want, tol=1e-9):
    assert got.dim() == 3 and got.shape[0] == len(want) and got.shape[1] == len(want[0])
    for b in range(len(want)):
        for l in range(len(want[b])):
            _assert_close_list([float(v) for v in got[b, l]], want[b][l], tol)


def _f64(name, key):
    return torch.tensor(EXPECTED[name][key], dtype=torch.float64)


# ---------- mode="svd_split" ----------


def check_svd_split(solve):
    A, B, ar = solve(mode="svd_split", U=_f64("F1", "U"), S=_f64("F1", "S"),
                     Vh=_f64("F1", "Vh"), r=4)
    assert ar == EXPECTED["F1"]["actual_r"] == 4
    _assert_close_2d(A, EXPECTED["F1"]["A"])
    _assert_close_2d(B, EXPECTED["F1"]["B"])
    # sqrt(S) 均分两侧: B @ A == U_r diag(S_r) V_r（秩 r 重构）
    rec = B @ A
    U, S, Vh = _f64("F1", "U"), _f64("F1", "S"), _f64("F1", "Vh")
    full = U[:, :4] @ torch.diag(S[:4]) @ Vh[:4, :]
    _assert_close_2d(rec, [list(map(float, row)) for row in full.tolist()])
    # √S 侧分配抽查: A 行范数 = B 列范数 = sqrt(S_i)
    for i in range(4):
        s = float(torch.sqrt(S[i]))
        assert _close(float(torch.norm(B[:, i])), s, 1e-8)
        assert _close(float(torch.norm(A[i, :])), s, 1e-8)

    # F2: r=8 超过短边 -> actual_r=4 截断
    A2, B2, ar2 = solve(mode="svd_split", U=_f64("F2", "U"), S=_f64("F2", "S"),
                        Vh=_f64("F2", "Vh"), r=8)
    assert ar2 == EXPECTED["F2"]["actual_r"] == 4
    assert A2.shape == (4, 4) and B2.shape == (5, 4)
    _assert_close_2d(A2, EXPECTED["F2"]["A"])
    _assert_close_2d(B2, EXPECTED["F2"]["B"])


