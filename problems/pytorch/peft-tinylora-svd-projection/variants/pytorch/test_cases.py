# ---------- mode="compute_R" ----------


def check_compute_R(solve):
    for name in ("F1", "F2"):
        v = _f64(name, "v")
        P = _f64(name, "P")
        R = solve(mode="compute_R", v=v, P=P)
        _assert_close_2d(R, EXPECTED[name]["R"])
    # 线性组合语义: 显式加权求和
    v = _f64("F1", "v")
    P = _f64("F1", "P")
    R1 = solve(mode="compute_R", v=v, P=P)
    manual = torch.zeros(4, 4, dtype=torch.float64)
    for i in range(v.shape[0]):
        manual += v[i] * P[i]
    assert torch.allclose(R1, manual)


