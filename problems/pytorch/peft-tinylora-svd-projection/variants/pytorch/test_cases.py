# ---------- mode="forward_delta" ----------


def check_forward_delta(solve):
    f = EXPECTED["F1"]
    A, B, R = _f64("F1", "A"), _f64("F1", "B"), _f64("F1", "R")
    x = torch.tensor(f["x"], dtype=torch.float64)
    got = solve(mode="forward_delta", x=x, tinylora_A=A, R=R, tinylora_B=B)
    _assert_close_3d(got, f["forward"])
    # 互证: x @ dW.T == forward（LoRA-XS 链 vs 合并形态）
    dW = solve(mode="delta_weight", tinylora_B=B, R=R, tinylora_A=A)
    lhs = x @ dW.T
    _assert_close_3d(lhs, f["forward"])


